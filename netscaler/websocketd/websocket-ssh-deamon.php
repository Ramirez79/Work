<?php
use Ratchet\Server\IoServer;
use Ratchet\Http\HttpServer;
use Ratchet\WebSocket\WsServer;
use wss\WsSSHConnector;

require __DIR__ . '/vendor/autoload.php'; // Loads the namespaces generated by composer

$server = IoServer::factory(
    new HttpServer(
        new WsServer(
            new WsSSHConnector()
        )
    ),
    9999, // websocket server port
    '127.0.0.1' // Listens only on loopback interface
);

$server->run(); // Runs the server in an infinite loop
